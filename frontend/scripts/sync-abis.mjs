// Regenerates src/abi/index.ts from the Foundry build output so the UI never drifts from the contracts.
// Run `forge build` in ../contracts first, then `pnpm sync-abis`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "contracts", "out");
const contracts = {
  escrowAbi: "AuctionEscrow",
  vaultAbi: "PaymentVault",
  tokenAbi: "MockToken",
  nftAbi: "DemoNFT",
};

let out = "// Generated by scripts/sync-abis.mjs from contracts/out. Do not edit by hand.\n\n";
for (const [name, contract] of Object.entries(contracts)) {
  const json = JSON.parse(readFileSync(join(root, `${contract}.sol`, `${contract}.json`), "utf8"));
  out += `export const ${name} = ${JSON.stringify(json.abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "..", "src", "abi", "index.ts"), out);
console.log("wrote src/abi/index.ts");
